/// Returns the real Unicode emoji string for a Noto Emoji [fileName], or `null`
/// if [fileName] is not in [notoEmojiUnicodeByFile].
String? findNotoEmojiUnicode(String fileName) =>
    notoEmojiUnicodeByFile[fileName];

/// Returns the Noto Emoji `.tgs` filename for a real Unicode [emoji] string,
/// matching both exact sequences and variation-selector (`U+FE0F`) variants.
String? findNotoEmojiFileName(String emoji) {
  if (emoji.isEmpty) return null;
  final exact = notoEmojiFileByUnicode[emoji];
  if (exact != null) return exact;
  if (emoji.contains('\uFE0F')) {
    final stripped = emoji.replaceAll('\uFE0F', '');
    return notoEmojiFileByUnicode[stripped] ??
        _notoEmojiFileByStrippedUnicode[stripped];
  }
  return _notoEmojiFileByStrippedUnicode[emoji];
}

