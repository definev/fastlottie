      uri: resolved,
      bytes: (json['bytes'] as num?)?.toInt() ?? 0,
      label: json['label'] as String? ?? (json['fileName'] as String),
      shortcode: json['shortcode'] as String?,
    );
  }

  final String id;
  final String packId;
  final String packTitle;
  final String fileName;
  final TgsItemKind kind;
  final String relativePath;
  final Uri uri;
  final int bytes;
  final String label;
  final String? shortcode;

  String get urlString => uri.toString();

  /// Returns the corresponding Unicode emoji character or sequence for this item
  /// if it is a bundled Noto Emoji (`emoji_u<codepoints>.tgs`), or `null` otherwise.
  String? get unicode {
    if (!fileName.startsWith('emoji_u') || !fileName.endsWith('.tgs')) {
      return null;
    }
    final hex = fileName.substring(7, fileName.length - 4);
    final codes = <int>[];
    for (final seg in hex.split('_')) {
      final val = int.tryParse(seg, radix: 16);
      if (val == null) return null;
      codes.add(val);
    }
    return String.fromCharCodes(codes);
  }

  Map<String, dynamic> toJson() => <String, dynamic>{
    'id': id,
    'packId': packId,
    'packTitle': packTitle,
    'fileName': fileName,
    'kind': kind.name,
    'url': relativePath,
    'bytes': bytes,
    'label': label,
    if (shortcode != null) 'shortcode': shortcode,
  };
}

